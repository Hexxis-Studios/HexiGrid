import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { KTX2Loader } from 'three/examples/jsm/loaders/KTX2Loader.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
// Allow only the vendor's fixed shadow stylesheet, never arbitrary inline CSS.
// JavaScript template literals normalize source line endings to LF.
const template = await readFile(path.join(root, 'node_modules/@google/model-viewer/lib/template.js'), 'utf8');
const styles = [...template.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(match => match[1].replace(/\r\n?/g, '\n'));
if (!styles.length || styles.some(style => style.includes('${') || style.includes('`') || style.includes('\\'))) throw new Error('Avatar stylesheet must be a fixed literal; review CSP generation.');
const hashes = styles.map(style => `'sha256-${createHash('sha256').update(style).digest('base64')}'`);
await build({
  stdin: { contents: "import '@google/model-viewer';", resolveDir: root, sourcefile: 'avatar-viewer-entry.js' },
  outfile: path.join(root, 'public', 'vendor', 'model-viewer.js'),
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  sourcemap: false,
  legalComments: 'external',
  plugins: [{ name: 'isolated-basis-worker', setup(builder) {
    builder.onLoad({ filter: /[\\/]KTX2Loader\.js$/ }, async ({ path: filename }) => {
      const original = await readFile(filename, 'utf8');
      const marker = 'this.workerSourceURL = URL.createObjectURL( new Blob( [ body ] ) );';
      if (original.split(marker).length !== 2) throw Error('Review changed vendor KTX2 worker construction.');
      return { contents: original.replace(marker, "this.workerSourceURL = '/vendor/basis/worker.js';"), loader: 'js', resolveDir: path.dirname(filename) };
    });
  } }]
});
await writeFile(path.join(root, 'lib/avatar-viewer-style-hashes.mjs'), `// Generated by scripts/build-avatar-viewer.mjs; exact bundled shadow styles only.\nexport const AVATAR_VIEWER_STYLE_HASHES = Object.freeze(${JSON.stringify(hashes)});\n`);
for (const [family, files] of Object.entries({
  draco: ['draco_decoder.js', 'draco_wasm_wrapper.js', 'draco_decoder.wasm'],
  basis: ['basis_transcoder.js', 'basis_transcoder.wasm']
})) {
  const output = path.join(root, 'public/vendor', family);
  await mkdir(output, { recursive: true });
  const source = path.join(root, 'node_modules/three/examples/jsm/libs', family, ...(family === 'draco' ? ['gltf'] : []));
  for (const filename of files) await copyFile(path.join(source, filename), path.join(output, filename));
}
// Basis embind generates JavaScript invokers. Isolate that exception in a fixed,
// network-disabled worker; never enable JavaScript eval in the owner document.
const basis = await readFile(path.join(root, 'public/vendor/basis/basis_transcoder.js'), 'utf8');
const worker = KTX2Loader.BasisWorker.toString();
const workerSource = [
  '// Generated pinned Three Basis worker; see THIRD-PARTY-NOTICES.md.',
  ...['EngineFormat', 'EngineType', 'TranscoderFormat', 'BasisFormat'].map(name => `let _${name} = ${JSON.stringify(KTX2Loader[name])};`),
  basis, worker.slice(worker.indexOf('{') + 1, worker.lastIndexOf('}'))
].join('\n');
await writeFile(path.join(root, 'public/vendor/basis/worker.js'), workerSource);
await copyFile(path.join(root, 'node_modules/@google/model-viewer/LICENSE'), path.join(root, 'public/vendor/LICENSE-APACHE-2.0.txt'));
