import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { serveStaticAsset } from '../lib/static-assets.mjs';

test('every static script referenced by the human and agent shells is actually served as JavaScript', async () => {
  const publicDir = fileURLToPath(new URL('../public/', import.meta.url));
  const html = await Promise.all(['index.html', 'agent-interface.html'].map(file => readFile(new URL(`../public/${file}`, import.meta.url), 'utf8')));
  const scripts = [...new Set(html.flatMap(source => [...source.matchAll(/<script\b[^>]*\bsrc="(\/[^"?#]+)"/g)].map(match => match[1])))];
  assert.ok(scripts.includes('/avatar-stage.js'));
  assert.ok(scripts.includes('/portrait-avatar.js'));
  for (const pathname of scripts) {
    // This sole dynamic script is generated from centralized brand constants
    // by the owner route rather than read from the static directory.
    if (pathname === '/brand.js') continue;
    let status, headers, bytes;
    const res = { writeHead(code, value) { status = code; headers = value; }, end(body) { bytes = body.length; } };
    const served = await serveStaticAsset({ method: 'GET', pathname, res, publicDir, securityHeaders: contentType => ({ 'content-type': contentType }), serveHtml: () => { throw new Error('Script served as HTML'); } });
    assert.equal(served, true, pathname);
    assert.equal(status, 200, pathname);
    assert.match(headers['content-type'], /javascript/, pathname);
    assert.ok(bytes > 0, pathname);
  }
});

test('every static asset in the offline shell resolves successfully before cache install', async () => {
  const publicDir = fileURLToPath(new URL('../public/', import.meta.url));
  const context = vm.createContext({ URL });
  context.globalThis = context;
  vm.runInContext(await readFile(new URL('../public/pwa-policy.js', import.meta.url), 'utf8'), context);
  for (const pathname of context.HexiGridPwaPolicy.SHELL_ASSETS) {
    if (pathname === '/brand.js') continue; // Generated by the owner route, not the static asset map.
    let status, headers, bytes;
    const res = { writeHead(code, value) { status = code; headers = value; }, end(body) { bytes = body.length; } };
    const served = await serveStaticAsset({ method: 'GET', pathname, res, publicDir,
      securityHeaders: contentType => ({ 'content-type': contentType }),
      serveHtml(response, filename) { status = 200; headers = { 'content-type': 'text/html' }; bytes = filename ? 1 : 0; response.end(Buffer.alloc(bytes)); }
    });
    assert.equal(served, true, pathname);
    assert.equal(status, 200, pathname);
    assert.ok(headers['content-type'], pathname);
    assert.ok(bytes > 0, pathname);
  }
});

test('the lazy VRM renderer and its CSP-safe stylesheet are served locally', async () => {
  const publicDir = fileURLToPath(new URL('../public/', import.meta.url));
  for (const [pathname, type] of [['/vendor/vrm-viewer.js', /javascript/], ['/vendor/vrm-viewer.css', /text\/css/]]) {
    let status, headers, body;
    const res = { writeHead(code, value) { status = code; headers = value; }, end(value) { body = value; } };
    assert.equal(await serveStaticAsset({ method: 'GET', pathname, res, publicDir, securityHeaders: contentType => ({ 'content-type': contentType }), serveHtml: () => { throw new Error('VRM asset served as HTML'); } }), true);
    assert.equal(status, 200);
    assert.match(headers['content-type'], type);
    assert.ok(body.length > 300);
  }
});
